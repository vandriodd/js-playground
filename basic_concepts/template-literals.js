// Template literals make working with strings more powerful and readable
// They allow us to embed expressions and create multiline strings easily
// Simply use backticks (``) instead of single or double quotes 😉

const name = "John";
const message = `Hello ${name}!`;
console.log(message);

// Multiline string
const multilineString = `This is a string
that spans multiple lines.`;
console.log(multilineString);
